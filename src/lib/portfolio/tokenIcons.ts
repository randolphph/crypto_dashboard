export function bundledTokenIconUrl(symbol: string): string | null {
  if (symbol.length > 64) return null;
  const raw = symbol.replace(/\([^)]+\)$/, '').trim().toUpperCase();
  const normalized = raw.startsWith('LD') && Object.hasOwn(BUNDLED_TOKEN_ICONS, raw.slice(2)) ? raw.slice(2) : raw;
  return Object.hasOwn(BUNDLED_TOKEN_ICONS, normalized) ? `/token-icons/${BUNDLED_TOKEN_ICONS[normalized]}` : null;
}
